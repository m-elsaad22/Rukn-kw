def inspection_list(noun, city, spec, areas, seed: int) -> str:
    a0, a1 = (areas + [city["name"]] * 2)[:2]
    bank = [
        f"عمر التشطيب الظاهر حول نقطة {noun}",
        f"أثر {spec['signs'][0]} هل هو حديث أم متكرر",
        f"وصول المعدات من باب {a0}",
        f"وجود حارس أو مواعيد إغلاق في {a1}",
        f"مصدر المياه والكهرباء قبل أي شطف أو فك",
        f"خامة الأرضية أو الجدار الملامس للعمل",
        f"آخر محاولة منزلية حتى لا تُكرر: {spec['mistakes'][0]}",
        f"تهوية المجلس إن كانت المواد ذات رائحة",
        f"ارتفاع العمل وهل يلزم تأمين إضافي",
        f"قرب اللوحة الكهربائية أو الغاز من نقطة التنفيذ",
        f"تصريف الماء بعيداً عن الكهرباء",
        f"أثر الغبار أو الملح حسب مناخ {city['name']}",
        f"نوع المبنى في {city['label']}",
        f"ضغط المياه أو ضعف الأدوار إن لزم",
        f"وقوف السيارات في وقت الزيارة",
        f"وجود أطفال أو حيوانات في منطقة {noun}",
        f"صور قبل التنفيذ للنقطة الظاهرة",
        f"المحابس أو القواطع التي قد تُغلق",
        f"حدود النطاق حتى لا يُضاف بند صامت",
        f"خدمة مرتبطة محتملة أثناء الفحص",
        f"حالة السطح أو الخزان إن كان الطلب يمسهما",
        f"الفواصل والشقوق حول {spec['signs'][1]}",
        f"رطوبة محيطة قد تعيد العرض بعد {noun}",
        f"وقت اليوم المناسب للخامة لا للسرعة",
        f"مسار المخلفات بعد التنفيذ",
        f"تجربة التشغيل أمامك قبل المغادرة",
        f"ما الذي تراقبه خلال 48 ساعة",
        f"موعد متابعة إن كانت الحالة تستدعيه",
        f"توافق الأداة مع الخامة: {'، '.join(spec['tools'][:2])}",
        f"عدم خلط مواد: {spec['mistakes'][1]}",
        f"توثيق الموديل أو الخامة قبل طلب قطعة",
        f"حدود التخصص المجاور خارج {noun}",
        f"الإضاءة أثناء الفحص حتى لا تُخفى العيوب",
        f"ميل التصريف أو الأرض إن وُجد ماء",
        f"غطاء الخزان أو فتحات الدكت إن لزم",
        f"واجهة أو حوش مكشوف للغبار",
        f"أبواب وممرات حتى لا تُخدش أثناء النقل",
        f"اتفاق مكتوب بالدينار الكويتي بعد الرؤية فقط",
        f"استثناءات النطاق: ما لن يُنفَّذ اليوم",
        f"سلامة السقف المستعار قبل أي فتح",
    ]
    start = seed % len(bank)
    step = 3 + (seed % 5)
    items = []
    seen = set()
    i = 0
    while len(items) < 12:
        it = bank[(start + i * step) % len(bank)]
        if it not in seen:
            seen.add(it)
            items.append(it)
        i += 1
        if i > 80:
            break
    lis = "".join(f"<li>{_e(x)}</li>" for x in items)
    return (
        f"<h2>{_e('قائمة فحص قبل بدء ' + noun + ' في ' + city['name'])}</h2>"
        f"<p>هذه القائمة تتغير حسب الوحدة. ليست بنوداً تُنفَّذ كلها في كل زيارة.</p>"
        f"<ul>{lis}</ul>"
    )


