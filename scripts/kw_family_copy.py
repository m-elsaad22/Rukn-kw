from __future__ import annotations

from html import escape


def _e(s: str) -> str:
    return escape(str(s))


def family_sections(family: str, noun: str, city: dict, spec: dict, areas, outline: int, seed: int) -> list[str]:
    a0, a1, a2 = (areas + [city["name"], city["name"], city["name"]])[:3]
    tools = "، ".join(spec["tools"])
    types = "، ".join(spec["types"])
    signs = spec["signs"]
    mistakes = spec["mistakes"]
    problem = spec["problem"]
    audience = spec["audience"]
    fn = _FAM.get(family, _generic)
    return fn(
        noun=noun,
        city=city,
        spec=spec,
        a0=a0,
        a1=a1,
        a2=a2,
        tools=tools,
        types=types,
        signs=signs,
        mistakes=mistakes,
        problem=problem,
        audience=audience,
        outline=outline,
        seed=seed,
    )


def _generic(**k):
    return _cleaning(**k)


def _p(h, *paras):
    body = "".join(f"<p>{_e(p)}</p>" for p in paras)
    return f"<h2>{_e(h)}</h2>{body}"


