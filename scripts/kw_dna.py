def faq_html(faqs) -> str:
    if not faqs:
        return ""
    parts = ['<h2>أسئلة شائعة حول هذه الخدمة</h2>', '<div class="rukn-grid cols-2">']
    for f in faqs:
        parts.append(
            '<div class="rukn-card">'
            f"<h3>{_e(f['question'])}</h3>"
            f"<p>{_e(f['answer'])}</p>"
            "</div>"
        )
    parts.append("</div>")
    return "".join(parts)
